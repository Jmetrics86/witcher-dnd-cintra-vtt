// Helper to convert an ArmorSet into a GameItem
export const armorSetToGameItem = (armor: ArmorSet, assignedToSchool?: WitcherSchool | 'DM_VAULT'): GameItem => ({
  id: armor.id,
  name: armor.name,
  category: 'armor',
  description: armor.description,
  rarity: armor.id.includes('tir-na-lia') ? 'Relic' : armor.id.includes('cintrian') ? 'Masterwork' : 'Witcher',
  valueGold: armor.valueGold,
  equipped: assignedToSchool !== 'DM_VAULT',
  armorClass: armor.armorClass,
  weightCategory: armor.weightCategory,
  properties: armor.perks,
  assignedToSchool: assignedToSchool || 'DM_VAULT',
});

